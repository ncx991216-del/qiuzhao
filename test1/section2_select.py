# ===== 1. 选取列 =====
df['姓名']          # 选一列 → 返回 Series（一维，带索引）
df[['姓名', '城市']]  # 选多列 → 返回 DataFrame（二维，注意是双层中括号）

# ===== 2. 选取行（loc 用标签名，iloc 用位置号）=====
df.loc[0]           # 选第0行（标签是0）
df.loc[0:2]         # 选第0~2行（注意：loc 的切片是"包含"末尾的！）
df.iloc[0:2]        # 选第0~1行（iloc 的切片"不包含"末尾，跟 Python 切片一样）

# ===== 3. 同时选行和列 =====
df.loc[0, '姓名']            # 第0行的姓名 → 张三
df.loc[[0, 1], ['姓名', '城市']]  # 第0、1行的姓名和城市

# ===== 4. 条件筛选（最实用！）=====
df[df['年龄'] > 28]                    # 年龄大于28的人
df[df['城市'] == '北京']               # 城市是北京的人
df[(df['年龄'] > 25) & (df['城市'] == '北京')]  # 两个条件：年龄>25 且 城市北京
                                          # 注意：& 表示"且"，每个条件要套括号！

# ===== 5. 选取特定值 =====
df['年龄'].max()    # 最大年龄
df['年龄'].min()    # 最小年龄
df['年龄'].mean()   # 平均年龄
